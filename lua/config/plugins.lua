		},
		config = function()
			require("config.plugins.lspconfig").setup()
		end,
	},

	{ -- Autoformat
		"stevearc/conform.nvim",
		event = { "BufWritePre" },
		cmd = { "ConformInfo" },
		keys = {
			{
				"<leader>f",
				function()
					require("conform").format({ async = true, lsp_format = "fallback" })
				end,
				mode = "",
				desc = "[F]ormat buffer",
			},
		},
		opts = require("config.plugins.conform").opts,
	},

	{ -- Autocompletion
		"saghen/blink.cmp",
		event = "VimEnter",
		version = "1.*",
		dependencies = {
			{
				"L3MON4D3/LuaSnip",
				version = "2.*",
				build = (function()
					return "make install_jsregexp"
				end)(),
			},
			"folke/lazydev.nvim",
		},
		opts = require("config.plugins.blink").opts,
	},
})
